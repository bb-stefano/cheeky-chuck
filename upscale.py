"""4x upscale of every game PNG with Real-ESRGAN (anime 6B, ONNX, CPU) -> name@4x.png next to the
original, plus game/imgsizes.lua (base sizes, for display.newImageRect in compat.lua).
Resumable: existing @4x files are skipped.  Run: python -I upscale.py [--only PATTERN] [--threads N]
"""
import sys, glob, os, time, argparse
import numpy as np
from PIL import Image
import onnxruntime as ort

ROOT = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(ROOT, "game")
DIRS = ["animpic", "uipic", "hints", "intro"]
MODEL = os.path.join(ROOT, "models", "RealESRGAN_x4plus_anime_6B.onnx")
TILE, PAD = 192, 12  # ponytail: CPU-friendly tiles; seams invisible at this overlap

ap = argparse.ArgumentParser()
ap.add_argument("--only", default=None, help="glob (relative to game/) to restrict the run")
ap.add_argument("--threads", type=int, default=4)
ap.add_argument("--sizes-only", action="store_true")
ap.add_argument("--requantize", action="store_true", help="palette-compress already produced @4x files")
args = ap.parse_args()

def all_pngs():
    out = []
    for d in DIRS:
        out += glob.glob(os.path.join(GAME, d, "**", "*.png"), recursive=True)
    out = [f for f in out if "@4x" not in os.path.basename(f)]
    if args.only:
        only = {os.path.normpath(f) for f in glob.glob(os.path.join(GAME, args.only), recursive=True)}
        out = [f for f in out if os.path.normpath(f) in only]
    return sorted(out)

def write_sizes(files):
    lines = ["-- generated by upscale.py: base (1x) pixel sizes, used by compat.lua to call newImageRect", "return {"]
    for f in files:
        rel = os.path.relpath(f, GAME).replace("\\", "/")
        w, h = Image.open(f).size
        lines.append(f'  ["{rel}"] = {{{w}, {h}}},')
    lines.append("}")
    open(os.path.join(GAME, "imgsizes.lua"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

def fill_transparent(rgb, a, passes=6):
    """Give fully transparent pixels the colour of their nearest opaque neighbours so the net doesn't
    smear the hidden (usually black) colour into the edges."""
    rgb = rgb.astype(np.float32); known = a > 0
    if known.all(): return rgb
    for _ in range(passes):
        acc = np.zeros_like(rgb); cnt = np.zeros(a.shape, np.float32)
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                if dx == 0 and dy == 0: continue
                sh = np.roll(np.roll(rgb, dy, 0), dx, 1); kn = np.roll(np.roll(known, dy, 0), dx, 1)
                acc += sh * kn[..., None]; cnt += kn
        fill = cnt > 0
        upd = (~known) & fill
        rgb[upd] = (acc[upd] / cnt[upd][:, None])
        known = known | fill
        if known.all(): break
    return rgb

def run_model(sess, img):  # img: HxWx3 float32 0..1 -> 4H x 4W x 3
    h, w, _ = img.shape
    out = np.zeros((h * 4, w * 4, 3), np.float32)
    for y0 in range(0, h, TILE):
        for x0 in range(0, w, TILE):
            y1, x1 = min(y0 + TILE, h), min(x0 + TILE, w)
            py0, px0, py1, px1 = max(y0 - PAD, 0), max(x0 - PAD, 0), min(y1 + PAD, h), min(x1 + PAD, w)
            tile = img[py0:py1, px0:px1].transpose(2, 0, 1)[None]
            res = sess.run(None, {sess.get_inputs()[0].name: tile})[0][0].transpose(1, 2, 0)
            oy, ox = (y0 - py0) * 4, (x0 - px0) * 4
            out[y0 * 4:y1 * 4, x0 * 4:x1 * 4] = res[oy:oy + (y1 - y0) * 4, ox:ox + (x1 - x0) * 4]
    return np.clip(out, 0, 1)

def upscale(sess, src, dst):
    im = Image.open(src).convert("RGBA")
    arr = np.asarray(im).astype(np.float32) / 255.0
    rgb, a = arr[..., :3], arr[..., 3]
    rgb = fill_transparent(rgb, a)
    up_rgb = run_model(sess, rgb)
    if (a < 1).any():
        up_a = run_model(sess, np.repeat(a[..., None], 3, axis=2)).mean(axis=2)
    else:
        up_a = np.ones(up_rgb.shape[:2], np.float32)
    out = np.concatenate([up_rgb, up_a[..., None]], axis=2)
    save_quantized(Image.fromarray((out * 255 + 0.5).astype(np.uint8), "RGBA"), dst)

def save_quantized(im, dst):
    """256-colour palette PNG: ~13% of the 32-bit size, visually identical for this flat cartoon art.
    Gradients band under a palette (the button panel did), so when the palette's mean error is above
    1/255 the file is saved in true colour instead."""
    q = im.quantize(256, method=Image.Quantize.FASTOCTREE)
    err = np.abs(np.asarray(q.convert("RGBA"), dtype=np.int16) - np.asarray(im.convert("RGBA"), dtype=np.int16)).mean()
    (q if err < 1.0 else im).save(dst, optimize=True)

if args.requantize:
    n = 0
    for f in all_pngs():
        dst = f[:-4] + "@4x.png"
        if os.path.exists(dst) and Image.open(dst).mode != "P":
            save_quantized(Image.open(dst).convert("RGBA"), dst); n += 1
    print("requantized", n); sys.exit(0)

files = all_pngs()
write_sizes(all_pngs() if args.only else files)
print(f"{len(files)} images; sizes table written")
if args.sizes_only: sys.exit(0)
so = ort.SessionOptions(); so.intra_op_num_threads = args.threads
sess = ort.InferenceSession(MODEL, so, providers=["CPUExecutionProvider"])
t0, done = time.time(), 0
for i, f in enumerate(files):
    dst = f[:-4] + "@4x.png"
    if os.path.exists(dst): continue
    upscale(sess, f, dst); done += 1
    if done % 25 == 0 or i == len(files) - 1:
        print(f"[{i + 1}/{len(files)}] {os.path.relpath(f, GAME)}  {time.time() - t0:.0f}s", flush=True)
print("done", done, "new files in", f"{time.time() - t0:.0f}s")
